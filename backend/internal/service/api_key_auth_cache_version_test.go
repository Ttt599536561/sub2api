// Both the custom Ultrafast snapshot and upstream image billing snapshot used v25.
// Neither shape is complete for the merged application, so both must be reloaded.
func TestAPIKeyService_RejectsV25AuthSnapshotBeforeMergedGroupPolicies(t *testing.T) {
	svc := &APIKeyService{}
	key, used, err := svc.applyAuthCacheEntry("k-legacy-v25", &APIKeyAuthCacheEntry{
		Snapshot: &APIKeyAuthSnapshot{Version: 25, Group: &APIKeyAuthGroupSnapshot{ID: 1}},
	})
	if err != nil {
		t.Fatalf("stale snapshot should be ignored without error: %v", err)
	}
	if used || key != nil {
		t.Fatal("v25 snapshot must be reloaded to obtain both image billing and Ultrafast policies")
	}
}
